# frozen_string_literal: true

require "json"
require "open3"
require "rbconfig"
require "tmpdir"

RSpec.describe DaisyUI::Tailwind::AppSources do
  subject(:sources) { described_class.new(components, **options) }

  let(:components) { [VariantsFixtures::Widget, VariantsFixtures::Picker] }
  let(:options)    { {} }
  let(:dir)        { Dir.mktmpdir("daisyui-app-sources") }

  after { FileUtils.rm_rf(dir) }

  def block(css, name) = css[%r{/\* #{Regexp.escape(name)} \*/\n@source inline\("([^"]*)"\);}, 1].to_s.split

  describe "#to_css" do
    let(:widget) { block(sources.to_css, "VariantsFixtures::Widget") }

    it "writes one block per component, sorted, under a header that names no version" do
      expect(sources.to_css).to start_with("/* Generated by daisyui-tailwind --app from the app's DaisyUI components: do not edit. */\n")
      expect(sources.to_css).not_to include(DaisyUI::VERSION)
      expect(sources.to_css.scan(%r{^/\* (\S+) \*/$}).flatten).to eq(%w[VariantsFixtures::Picker VariantsFixtures::Widget])
    end

    it "gives the hover: and open-dropdown forms of every `on` class" do
      fixtures = VariantsFixtures
      expected = [fixtures::FILL, fixtures::OUTLINE, fixtures::CLEAR].flat_map { |classes| ["hover:#{classes}", "#{fixtures::OPEN}:#{classes}"] }

      expect(widget).to include(*expected)
    end

    it "gives the base, the members, the compounds and the slots" do
      picker = block(sources.to_css, "VariantsFixtures::Picker")

      expect(widget).to include("btn", "font-medium", "btn-sm", "[--fontsize:var(--text-sm)]", *VariantsFixtures::QUIET.split)
      expect(picker).to include("dropdown", "picker-trigger", "mt-2", "picker-wide", "w-96", "w-48", "btn-block", "#{VariantsFixtures::OPEN}:shadow-lg")
    end

    it "does not depend on the order it is given the components" do
      expect(described_class.new(components.reverse).to_css).to eq(sources.to_css)
    end

    it "is byte-identical from one process to the next" do
      exe = File.join(DaisyUI::Tailwind::ROOT, "exe", "daisyui-tailwind")
      fixtures = File.join(DaisyUI::Tailwind::ROOT, "spec", "support", "variants_fixtures.rb")
      runs = Array.new(2) { Open3.capture3(RbConfig.ruby, exe, "--app", "--require", fixtures) }

      expect(runs.map(&:last)).to all(be_success)
      expect(runs.first.first).to include("/* VariantsFixtures::Widget */").and eq(runs.last.first)
    end

    it "raises for an anonymous class, which has no name to label its block" do
      expect { described_class.new([VariantsFixtures::Thing, Class.new(DaisyUI::Base)]) }
        .to raise_error(ArgumentError, /anonymous/)
    end

    context "with a prefix" do
      let(:options) { { prefix: "d-" } }

      it "prefixes each class after its state, as the component renders it" do
        expect(widget).to include("d-btn", "d-font-medium", "hover:d-#{VariantsFixtures::CLEAR}")
        expect(widget).not_to include("btn")
      end
    end

    context "with responsive breakpoints" do
      let(:options) { { responsive: %w[sm] } }

      it "adds them to the component class and the modifiers" do
        expect(widget).to include("sm:btn", "sm:btn-sm", "sm:[--fontsize:var(--text-sm)]")
      end
    end

    context "without components" do
      let(:components) { [] }

      it "says so" do
        expect(sources.to_css).to include("/* No app components. */")
        expect(sources.to_css).not_to include("@source")
      end
    end

    it "raises for a class Tailwind cannot read from @source inline(…)" do
      broken = Class.new(DaisyUI::Base) { variants { base "w-[calc(100%" } }
      stub_const("BrokenWidget", broken)

      expect { described_class.new([broken]).to_css }.to raise_error(ArgumentError, /BrokenWidget.*"w-\[calc\(100%"/)
    end
  end

  describe "#to_json" do
    it "lists each component's classes and all of them together" do
      json = JSON.parse(sources.to_json)

      expect(json["components"].keys).to eq(%w[VariantsFixtures::Picker VariantsFixtures::Widget])
      expect(json["components"]["VariantsFixtures::Widget"]).to include("name" => "btn", "classes" => include("font-medium"))
      expect(json["classes"]).to eq(json["classes"].uniq.sort)
    end
  end

  # What the issue is for: Tailwind only compiles classes it finds written out.
  it "gives Tailwind classes it compiles into the state rules" do
    require "tailwindcss/ruby"

    File.write(File.join(dir, "app.css"), sources.to_css)
    File.write(File.join(dir, "input.css"), %(@import "tailwindcss" source(none);\n@import "./app.css";\n))
    _out, err, status = Open3.capture3(Tailwindcss::Ruby.executable, "-i", "input.css", "-o", "output.css", chdir: dir)
    css = File.read(File.join(dir, "output.css"))

    expect(status).to be_success, err
    expect(css).to match(/\.dropdown:is\(:focus-within,\s*\[open\],\s*:has\(:popover-open\)\)\s*>\s*\S+:z-10 \{\n\s+z-index: 10;/)
    expect(css).to match(/@media \(hover: hover\) \{\n\s+\.hover\\:\S+:hover \{/)
    # CLEAR, once under :hover and once inside the open dropdown.
    expect(css.scan("--btn-bg: color-mix(in oklab,var(--color-base-content) 8%,transparent);").size).to eq(2)
  end
end
