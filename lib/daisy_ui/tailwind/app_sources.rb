# frozen_string_literal: true

module DaisyUI
  module Tailwind
    # The Tailwind sources for an app's own components (DaisyUI::Base
    # subclasses outside the gem), read from their declarations rather than
    # the gem's manifest: the component class, every modifier, and what a
    # `variants` block declares, `on` rules written out once per state. Those
    # state-prefixed classes appear nowhere literally in the app's source, so
    # Tailwind only compiles them from here.
    #
    # One `@source inline(…)` per component, sorted by name, under a header
    # with no version, so the file changes only when a declaration does: it
    # is meant to be committed, and DaisyUI::Tailwind.stale? checks it.
    class AppSources
      HEADER = "/* Generated by daisyui-tailwind --app from the app's DaisyUI components: do not edit. */\n"

      def initialize(components, responsive: [], prefix: nil)
        anonymous = components.reject(&:name)
        raise ArgumentError, "an anonymous class has no name to label its block: #{anonymous.inspect}" unless anonymous.empty?

        @components = components.sort_by(&:name)
        @breakpoints = responsive.map(&:to_s)
        @prefix = prefix.to_s
        Sources.validate_options!(@breakpoints, @prefix)
      end

      def render(format)
        case format.to_s
        when "css" then to_css
        when "json" then to_json
        else raise ArgumentError, "unknown format #{format.inspect}: css or json"
        end
      end

      def to_css
        return "#{HEADER}/* No app components. */\n" if @components.empty?

        lines = @components.flat_map { |component| ["/* #{component.name} */", %(@source inline("#{classes(component).join(' ')}");)] }
        "#{HEADER}#{lines.join("\n")}\n"
      end

      def to_json(*)
        require "json"

        components = @components.to_h do |component|
          [component.name, { "name" => component.component_class&.to_s, "classes" => classes(component) }]
        end
        json = { "components" => components, "classes" => components.values.flat_map { |entry| entry["classes"] }.uniq.sort }
        "#{JSON.pretty_generate(json)}\n"
      end

      private

      def classes(component)
        classes = component.variants.literal_classes(prefix: @prefix) + responsive_classes(component)
        invalid = classes.reject { |token| Candidate.valid?(token) }
        return classes.uniq.sort if invalid.empty?

        raise ArgumentError, "#{component.name} declares #{invalid.map(&:inspect).join(', ')}, " \
                             "which Tailwind cannot read from @source inline(…)"
      end

      # What `responsive:` renders: the component class and the modifiers.
      def responsive_classes(component)
        return [] if @breakpoints.empty?

        tokens = [component.component_class&.to_s, *(component.modifiers || {}).values].compact.flat_map(&:split)
        @breakpoints.flat_map { |breakpoint| tokens.map { |token| "#{breakpoint}:#{@prefix}#{token}" } }
      end
    end
  end
end
