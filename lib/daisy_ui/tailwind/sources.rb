# frozen_string_literal: true

module DaisyUI
  module Tailwind
    # Renders the Tailwind sources for a set of (resolved) components:
    #
    # - `to_css`: a partial for the app's Tailwind entry to @import, one
    #   `@source inline("…")` per component after base.rb's shared classes. It
    #   names no path, so it is the same on every machine.
    # - `to_json`: the same for a build script, plus each component's absolute
    #   files for anyone who wants a literal `@source` instead.
    #
    # `responsive:` adds `<breakpoint>:` variants of the classes `responsive:`
    # renders (a component's own class and its modifiers). `prefix:` mirrors
    # DaisyUI.configuration.prefix: the component class and modifiers always
    # render prefixed, while a class string in a component's Ruby may render
    # either way (`component_classes("card-body")` is prefixed, Tooltip's
    # "after:hidden" is not), so those are given both ways.
    class Sources
      BREAKPOINT = /\A@?[a-z0-9][a-z0-9-]*\z/
      PREFIX = /\A[^\s"'`;{}\\]+\z/

      attr_reader :components

      # @api private Shared with AppSources.
      def self.validate_options!(breakpoints, prefix)
        breakpoints.each do |breakpoint|
          raise ArgumentError, "invalid breakpoint #{breakpoint.inspect}: give the variant name, e.g. sm or @md" unless BREAKPOINT.match?(breakpoint)
        end
        return if prefix.empty? || PREFIX.match?(prefix)

        raise ArgumentError, "invalid prefix #{prefix.inspect}"
      end

      def initialize(manifest, components, responsive: [], prefix: nil)
        @manifest = manifest
        @components = components
        @breakpoints = responsive.map(&:to_s)
        @prefix = prefix.to_s
        validate!
      end

      def render(format)
        case format.to_s
        when "css" then to_css
        when "json" then to_json
        else raise ArgumentError, "unknown format #{format.inspect}: css or json"
        end
      end

      def to_css
        header = "/* Generated by daisyui-tailwind (daisyui #{VERSION}): do not edit. */\n"
        return "#{header}/* No DaisyUI components referenced. */\n" if components.empty?

        lines = [
          "/* daisyUI components: #{components.join(', ')} */",
          "/* Shared by every component (lib/daisy_ui/base.rb) */",
          inline(shared_classes)
        ]
        components.each { |name| lines.push("/* #{@manifest.components.fetch(name)['class']} */", inline(classes(name))) }
        "#{header}#{lines.join("\n")}\n"
      end

      def to_json(*)
        require "json"

        "#{JSON.pretty_generate(json)}\n"
      end

      private

      def json
        files = @manifest.shared_files + @manifest.files(components)
        {
          "daisyui" => VERSION,
          "components" => components.to_h { |name| [name, component_json(name)] },
          "shared" => { "files" => @manifest.shared_files, "classes" => shared_classes },
          "classes" => (shared_classes + components.flat_map { |name| classes(name) }).uniq.sort,
          "files" => files.uniq.sort
        }
      end

      def component_json(name)
        entry = @manifest.components.fetch(name)
        entry.slice("class", "name", "depends_on").merge("files" => @manifest.files([name]), "classes" => classes(name))
      end

      def classes(name)
        entry = @manifest.components.fetch(name)
        expand(entry["classes"], [entry["name"], *entry["modifiers"]].compact)
      end

      def shared_classes = expand(@manifest.shared["classes"], @manifest.shared["classes"])

      def expand(classes, responsive)
        prefixed = classes.map { |token| "#{@prefix}#{token}" }
        prefixed += classes - responsive unless @prefix.empty?
        prefixed + @breakpoints.flat_map { |breakpoint| responsive.map { |token| "#{breakpoint}:#{@prefix}#{token}" } }
      end

      def inline(classes) = %(@source inline("#{classes.join(' ')}");)

      def validate! = self.class.validate_options!(@breakpoints, @prefix)
    end
  end
end
